export type DanciWordItem = {
  id: string;
  word: string;
  meaning: string;
  unit: string;
  level: 1 | 2 | 3;
  family: string;
  example: string;
  tip: string;
};

export type DanciWordPack = {
  id: string;
  label: string;
  shortLabel: string;
  description: string;
  words: DanciWordItem[];
};

type WordSeed = [
  word: string,
  meaning: string,
  unit: string,
  level: 1 | 2 | 3,
  family: string,
  example: string,
  tip: string,
];

function createPack(
  id: string,
  label: string,
  shortLabel: string,
  description: string,
  seeds: WordSeed[],
): DanciWordPack {
  return {
    id,
    label,
    shortLabel,
    description,
    words: seeds.map(([word, meaning, unit, level, family, example, tip]) => ({
      id: `${id}:${word.toLowerCase().replace(/[^a-z]/g, "")}`,
      word,
      meaning,
      unit,
      level,
      family,
      example,
      tip,
    })),
  };
}

